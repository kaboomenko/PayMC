function onlineCurve(peak: number, base: number, nowHour = 12) {
  // 24 samples ending at the current hour, evening peak around 21:00 MSK
  const out: number[] = [];
  for (let i = 23; i >= 0; i--) {
    const h = (nowHour - i + 24) % 24;
    const x = Math.cos(((h - 21) / 24) * Math.PI * 2); // 1 at 21:00
    const night = h >= 3 && h <= 8 ? 0.55 : 1;
    out.push(Math.round((base + (peak - base) * ((x + 1) / 2)) * night));
  }
  return out;
}

